def set_lang(code):
    LANG["code"] = "en" if code == "en" else "ar"


def is_rtl():
    return LANG["code"] == "ar"


def t(key, **kw):
    pair = TEXT.get(key)
    if pair is None:
        return key
    s = pair[1] if LANG["code"] == "en" else pair[0]
    return s.format(**kw) if kw else s


def embed(text):
    """يعزل اتجاه نص يدخله المستخدم (اسم خانة) داخل جملة، حتى لا تختلط أرقامه بالجملة."""
    text = str(text)
    rtl_text = any("؀" <= ch <= "ۿ" for ch in text)
    return ("‫" if rtl_text else "‪") + text + "‬"


